/*
 * bundle.mjs — builds dist/vicehaven.html, the whole game in one file.
 *
 *   node tools/bundle.mjs
 *
 * Plain Node 18+, no packages. It reads index.html and replaces every local
 * stylesheet <link> with a <style> block and every local <script src> with
 * an inline <script>, in the same order, so the page boots exactly as the
 * folder version does. The result can be emailed, copied to a USB stick or
 * double-clicked from Downloads and it runs in Edge with nothing else.
 *
 * Each inlined script ends with a //# sourceURL comment, so errors and the
 * DevTools Sources panel still show the original file names.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'dist');
const outFile = path.join(outDir, 'vicehaven.html');

const read = (rel) => {
  const file = path.join(root, rel);
  if (!fs.existsSync(file)) throw new Error('bundle: ' + rel + ' is referenced by index.html but does not exist');
  return fs.readFileSync(file, 'utf8');
};

// Inside a <script> element the HTML parser only looks for "</script". The
// usual fix, "<\/script", means the same thing in a JavaScript string, regex
// or template, so the code runs unchanged. ("<!--" followed by "<script" can
// also hide the closing tag; none of the game's files contain that, and the
// build refuses to guess if one ever does.)
const safeScript = (code, rel) => {
  if (/<!--/.test(code) && /<script/i.test(code)) throw new Error('bundle: ' + rel + ' contains "<!--" and "<script"; split those strings before inlining');
  return code.replace(/<\/(script)/gi, '<\\/$1');
};
const safeStyle = (css, rel) => {
  if (/<\/style/i.test(css)) throw new Error('bundle: ' + rel + ' contains "</style"');
  return css;
};

let html = read('index.html');
const counts = { css: 0, js: 0, bytes: 0 };

html = html.replace(/<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/?>/g, (tag, href) => {
  if (/^[a-z]+:/i.test(href)) return tag; // leave remote stylesheets alone
  const css = safeStyle(read(href), href);
  counts.css++;
  counts.bytes += css.length;
  return '<style data-src="' + href + '">\n' + css.trimEnd() + '\n</style>';
});

html = html.replace(/<script\s+src="([^"]+)"[^>]*>\s*<\/script>/g, (tag, src) => {
  if (/^[a-z]+:/i.test(src)) return tag;
  const code = safeScript(read(src), src);
  counts.js++;
  counts.bytes += code.length;
  return '<script data-src="' + src + '">\n' + code.trimEnd() + '\n//# sourceURL=' + src + '\n</script>';
});

const leftovers = html.match(/<(?:script|link)[^>]*\s(?:src|href)="(?![a-z]+:)[^"]+"/gi);
if (leftovers) throw new Error('bundle: some local files were not inlined:\n  ' + leftovers.join('\n  '));

// Mark the single-file build so it can be told apart in bug reports.
html = html.replace('<html lang="en">', '<html lang="en" data-build="single-file">');
const stamp = new Date().toISOString().slice(0, 10);
html = html.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n  <!-- Vicehaven single-file build, ' + stamp + '. Generated by tools/bundle.mjs from index.html; edit the source files, not this. -->');

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, html);
const size = fs.statSync(outFile).size;
console.log('[bundle] ' + path.relative(root, outFile) + ': ' + counts.js + ' scripts, ' + counts.css + ' stylesheets, ' + (size / 1048576).toFixed(2) + ' MB');
